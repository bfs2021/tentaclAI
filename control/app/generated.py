"""compose.generated.yaml – mounts derived from services/*.json (docker services with mode "socket").

The claude container gets Docker access only through such services:
  socket  -> /run/tentaclai/docker-<name>.sock   (svc creates a docker context <name> for it)
  stacks  -> same path as on the host             (so docker compose resolves relative bind mounts)
"""
import json
import os
import re
import sys

try:
    import tclib
except ImportError:  # run directly from a checkout (tentaclai.sh init) – use lib/ of the repository
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "lib"))
    import tclib

HEADER = "# generated by tentacontrol from services/*.json (docker services, mode socket) – do not edit by hand\n"


def mounts(stack_dir):
    env = tclib.read_env(os.path.join(stack_dir, ".env"))
    res, seen = [], set()
    for fname, svc in tclib.load_services(os.path.join(stack_dir, "services")).items():
        d = svc.get("docker")
        if not d or not tclib.enabled(svc) or d.get("mode", "socket") != "socket":
            continue
        name = svc.get("name") or fname
        sock = tclib.render(d.get("socket", "/var/run/docker.sock"), env)
        stacks = tclib.render(d.get("stacks_dir", ""), env)
        for m in (f"{sock}:/run/tentaclai/docker-{name}.sock", f"{stacks}:{stacks}" if stacks else None):
            if m and m not in seen and not m.startswith(":"):
                seen.add(m)
                res.append(m)
    return res


def render(stack_dir):
    ms = mounts(stack_dir)
    if not ms:
        return HEADER + "services: {}\n"
    return HEADER + "services:\n  claude:\n    volumes:\n" + "".join(f"      - {m}\n" for m in ms)


def write(stack_dir):
    """returns True when the file changed (claude container must be recreated)"""
    path = os.path.join(stack_dir, "compose.generated.yaml")
    new = render(stack_dir)
    try:
        old = open(path).read()
    except FileNotFoundError:
        old = None
    if old == new:
        return False
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(new)
    os.replace(tmp, path)
    return True


if __name__ == "__main__":
    d = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("STACK_DIR", ".")
    print("changed" if write(d) else "unchanged")
